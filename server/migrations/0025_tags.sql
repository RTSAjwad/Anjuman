-- US-6.1 — note tags (teacher/admin-authored, shared note taxonomy).
--
-- Normalised join-table storage (stage-6 decision): a canonical `tags` table keyed
-- by id, plus `note_tags` linking notes to tags. The Anki `::` hierarchy is carried
-- *in the tag name* (`biology::cells` is one `name`), so rename is a single row
-- update and subtag/prefix matching is a string prefix on `name`.
--
-- Tags are NOTE-scoped, not school-scoped: there is deliberately no `school_id`
-- here, because tags travel with a note if its deck is ever shared across
-- schools (organisation preserved). Visibility is governed by the notes a user
-- can already see, not a tag-scoping layer.

CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE note_tags (
    note_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,

    PRIMARY KEY (note_id, tag_id),

    FOREIGN KEY (note_id) REFERENCES notes(id) ON DELETE CASCADE,
    FOREIGN KEY (tag_id) REFERENCES tags(id) ON DELETE CASCADE
);

CREATE INDEX idx_note_tags_tag ON note_tags(tag_id);
